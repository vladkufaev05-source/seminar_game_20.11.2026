std::string trim(const std::string& str) {
    size_t first = str.find_first_not_of(" \t\r\n");
    if (std::string::npos == first) return "";
    size_t last = str.find_last_not_of(" \t\r\n");
    return str.substr(first, (last - first + 1));
}

int readChoice(int min_val, int max_val) {
    std::string line;
    if (!std::getline(std::cin, line)) return -1;
    std::string trimmed = trim(line);
    if (trimmed.length() == 1 && std::isdigit(static_cast<unsigned char>(trimmed[0]))) {
        int val = trimmed[0] - '0';
        if (val >= min_val && val <= max_val) return val;
    }
    return -2;
}

void waitForEnter() {
    while (true) {
        std::string line;
        if (!std::getline(std::cin, line)) {
            std::cout << "\n[Игра прервана (EOF)]\n";
            std::exit(0);
        }
        if (trim(line).empty()) break;
        std::cout << "Нажмите Enter для продолжения.\n";
    }
}

