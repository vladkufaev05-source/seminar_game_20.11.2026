void showResult(int correct_count, int score) {
    std::cout << "\nРезультаты игры\n";
    std::cout << "Правильно: " << correct_count << " из 10\n";
    std::cout << "Баллы: " << score << " из 100\n";
    std::string grade;
    if (score >= 90) grade = "Отличное понимание темы";
    else if (score >= 70) grade = "Уверенное понимание материала";
    else if (score >= 50) grade = "Базовые знания, рекомендуется повторение";
    else grade = "Стоит повторить материал";
    std::cout << "Оценка: " << grade << "\n";
    std::cout << "\nНажмите Enter для возврата в меню";
    waitForEnter();
}

