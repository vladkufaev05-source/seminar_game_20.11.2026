void playGame(const std::vector<Question>& questions) {
    int score = 0, correct_count = 0;
    for (size_t i = 0; i < questions.size(); ++i) {
        const auto& q = questions[i];
        std::cout << "Вопрос " << (i + 1) << "/10\n";
        std::cout << q.condition << "\n";
        if (!q.code.empty()) std::cout << "Код:\n" << q.code << "\n";
        for (const auto& opt : q.options) std::cout << opt << "\n";

        int choice = 0;
        while (true) {
            std::cout << "Ваш ответ (1-3): ";
            int res = readChoice(1, 3);
            if (res == -1) { std::cout << "\n[Игра прервана (EOF)]\n"; return; }
            if (res == -2) { std::cout << "Недопустимый ввод. Введите одну цифру от 1 до 3.\n"; continue; }
            choice = res; break;
        }

        if (choice == q.correct) {
            std::cout << "Верно.\n"; correct_count++; score += 10;
        }
        else {
            std::cout << "Неверно.\n";
        }
        std::cout << "Правильный ответ: " << q.options[q.correct - 1] << "\n";
        std::cout << "Пояснение: " << q.explanation << "\n";
        std::cout << "\nНажмите Enter для продолжения";
        waitForEnter();
    }
    showResult(correct_count, score);
}

